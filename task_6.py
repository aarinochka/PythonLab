day = int(input("Введите день вашего рождения: "))
month = int(input("Введите номер месяца вашего рождения: "))
zz = ["Козерог","Водолей","Рыбы","Овен","Телец","Близнецы","Рак","Лев","Дева","Весы","Скорпион","Стрелец", "Козерог"]
last_day_zz = [20,18,20,19,20,20,22,22,22,22,21,21]
count_day_in_month = [31,29,31,30,31,30,31,31,30,31,30,31]
if 0 <= month <= 12 and 0 <= day <= count_day_in_month[month-1]:
    if day < last_day_zz[month-1]:
        print(f"Ваш знак зодиака: {zz[month-1]}")
    else:
        print(f"Ваш знак зодиака: {zz[month]}")
else:
    print("Такой даты не существует!")        

