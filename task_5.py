a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
print(f"Сумма: {a+b:.2f}")
print(f"Разность: {a-b:.2f}")
print(f"Произведение: {a*b:.2f}")
if b ==0:
    print("второе = 0: делеить на ноль нельзя")
else:    
    print(f"Частное: {a/b:.2f}")
print(f"Остаток от деления первого на второе: {a%b:.2f}")
print(f"первое в степени второго: {a**b:.2f}")